test("Resend and Expo mocks track partial delivery and escape user-provided email content", async (t) => {
  const w = workspace(t);
  w.exec(
    "INSERT INTO device_push_tokens(id,user_id,expo_push_token) VALUES ('device','owner','ExponentPushToken[test]')",
  );
  t.mock.method(globalThis, "fetch", async (url, init) => {
    if (url === "https://api.resend.com/emails") {
      const body = JSON.parse(init.body);
      assert.equal(body.html.includes("&lt;script&gt;"), true);
      assert.equal(body.html.includes("<script>"), false);
      return Response.json({ message: "Domain not verified" }, { status: 403 });
    }
    assert.equal(url, "https://exp.host/--/api/v2/push/send");
    return Response.json({ data: { status: "ok", id: "push-ticket" } });
  });
  const result = await deliverNotification(w.env, {
    userId: "owner",
    type: "published",
    title: "<script>",
    body: "Launch",
  });
  assert.equal(result.status, "partial");
  assert.equal(
    w.row("SELECT provider_message_id FROM notification_deliveries WHERE channel='push'")
      .provider_message_id,
    "push-ticket",
  );
  assert.equal(
    w.row("SELECT status FROM notification_deliveries WHERE channel='email'").status,
    "failed",
  );
});

async function publishingFixture(t) {
  const w = workspace(t);
  w.post("publish", "client-a", "calendar_scheduled");
  w.objects.set("graphic.jpg", "fixture image");
  w.exec(
    "INSERT INTO social_accounts(id,client_id,platform,external_account_id,status,access_token_ciphertext) VALUES ('social','client-a','facebook','fixture-page','connected',?)",
    await encryptSecret("fixture-token", w.env),
  );
  w.exec(
    "UPDATE posts SET social_account_id='social',graphic_key='graphic.jpg' WHERE id='publish'",
  );
  await w.request("/v1/posts/publish/publish-now", { user: "owner", method: "POST" });
  return w;
}

test("Meta queue mock confirms publication once despite duplicate deliveries and notifies owners", async (t) => {
  const w = await publishingFixture(t);
  let calls = 0,
    acknowledged = 0;
  t.mock.method(globalThis, "fetch", async (url) => {
    if (url.startsWith("https://graph.facebook.com/")) {
      calls++;
      return Response.json({ id: "photo", post_id: "published-id" });
    }
    assert.equal(url, "https://api.resend.com/emails");
    return Response.json({ id: "email-id" });
  });
  const message = {
    body: w.published[0],
    attempts: 1,
    ack() {
      acknowledged++;
    },
    retry() {
      throw new Error("Unexpected retry");
    },
  };
  await worker.queue({ messages: [message, message] }, w.env);
  assert.equal(calls, 1);
  assert.equal(acknowledged, 2);
  assert.equal(w.row("SELECT status FROM posts WHERE id='publish'").status, "published");
  assert.equal(w.row("SELECT status FROM publish_jobs").status, "completed");
  assert.equal(w.row("SELECT status FROM notifications WHERE type='published'").status, "sent");
});

test("provider rate limit retries without reporting the post as published", async (t) => {
  const w = await publishingFixture(t);
  t.mock.method(globalThis, "fetch", async () =>
    Response.json(
      { error: { message: "Rate limit", code: 4 } },
      { status: 429, headers: { "retry-after": "120" } },
    ),
  );
  let retry;
  await worker.queue(
    {
      messages: [
        {
          body: w.published[0],
          attempts: 1,
          ack() {
            throw new Error("Should retry");
          },
          retry(options) {
            retry = options;
          },
        },
      ],
    },
    w.env,
  );
  assert.equal(retry.delaySeconds >= 60, true);
  assert.equal(w.row("SELECT status FROM publish_jobs").status, "retrying");
  assert.equal(w.row("SELECT status FROM posts WHERE id='publish'").status, "publish_queued");
});
