const options = {
  instructions: "Use brand rules",
  content: [{ type: "input_text", text: "Caption" }],
  schemaName: "test",
  schema: { type: "object" },
};

test("OpenAI mock verifies strict structured requests and response provenance", async (t) => {
  let sent;
  t.mock.method(globalThis, "fetch", async (url, init) => {
    assert.equal(url, "https://api.openai.com/v1/responses");
    sent = JSON.parse(init.body);
    assert.equal(init.headers.authorization, "Bearer fixture-key");
    return Response.json(
      {
        id: "response-1",
        output: [{ content: [{ type: "output_text", text: '{"caption":"On brand"}' }] }],
        usage: { output_tokens: 8 },
      },
      { headers: { "x-request-id": "request-1" } },
    );
  });
  const result = await createStructuredResponse({ OPENAI_API_KEY: "fixture-key" }, options);
  assert.equal(sent.text.format.strict, true);
  assert.equal(sent.text.format.name, "test");
  assert.equal(result.data.caption, "On brand");
  assert.equal(result.requestId, "request-1");
  assert.equal(result.responseId, "response-1");
});

test("OpenAI empty, malformed JSON and HTTP failures become actionable errors", async (t) => {
  const scenarios = [
    [Response.json({ output_text: "" }), /no structured text/],
    [Response.json({ output_text: "invalid-json" }), /invalid structured JSON/],
    [
      new Response("Rate limited", { status: 429, headers: { "x-request-id": "rate-test" } }),
      /429.*rate-test/,
    ],
  ];
  for (const [response, expected] of scenarios) {
    t.mock.method(globalThis, "fetch", async () => response);
    await assert.rejects(
      createStructuredResponse({ OPENAI_API_KEY: "fixture-key" }, options),
      expected,
    );
    t.mock.restoreAll();
  }
});

